/**
 * Universal translation function supporting dot-notation keys and dynamic variable injection.
 * Throws a loud descriptive error if a key is missing to satisfy zero-silent-fallback rules.
 */
export function translate(
  language: SupportedLanguage,
  key: string,
  variables?: Record<string, string | number>
): string {
  const dictionary = i18nDictionary[language];
  if (!dictionary) {
    throw new Error(`[i18n] Unsupported language: "${language}"`);
  }

  const templateString = dictionary[key];
  if (templateString === undefined) {
    throw new Error(`[i18n] Missing translation key: "${key}" for language: "${language}"`);
  }

  if (!variables) {
    return templateString;
  }

  return Object.entries(variables).reduce((interpolated, [varKey, varVal]) => {
    return interpolated.replace(new RegExp(`\\{${varKey}\\}`, 'g'), String(varVal));
  }, templateString);
}
